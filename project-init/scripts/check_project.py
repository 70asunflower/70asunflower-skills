def fix_project(root: Path, model: str, rows: list[tuple[str, str, str]] | None,
                header: dict[str, str]) -> list[str]:
    """--fix：只做无争议修复（补目录/记忆/日志/顶层文档/功能文档骨架）。"""
    actions: list[str] = []
    now = datetime.now()
    today = now.strftime("%Y-%m-%d")
    stamp = now.strftime("%Y-%m-%d %H:%M")
    who = model or "未声明（check --fix 补建）"

    def entry(title: str, summary: str) -> str:
        return f"## {stamp} — {title}\n- 模型：{who}\n- 摘要：{summary}\n- 原因：巡检发现缺失，自动补建\n"

    # 1) 结构表声明的目录
    for p, _, _ in rows or []:
        if p.endswith("/") and not (root / p.rstrip("/")).is_dir():
            (root / p.rstrip("/")).mkdir(parents=True, exist_ok=True)
            actions.append(f"补建目录 {p}")

    # 2) 项目记忆与当日日志
    mem = root / "memory"
    mem.mkdir(exist_ok=True)
    if not (mem / "MEMORY.md").exists():
        (mem / "MEMORY.md").write_text(MEMORY_STUB, encoding="utf-8", newline="\n")
        actions.append("补建 memory/MEMORY.md")
    log = mem / f"{today}.md"
    if not log.exists():
        log.write_text(entry("巡检补建", "补建当日日志"), encoding="utf-8", newline="\n")
        actions.append(f"补建 memory/{today}.md")

    # 3) 逐文件日志模式：给缺日志的正式文件补建
    if header.get("日志模式", "") == "逐文件":
        for p, _, tracked in rows or []:
            base = root / p.rstrip("/")
            if not p.endswith("/") or tracked != "是" or p.rstrip("/") in ("memory", "tmp"):
                continue
            if not base.is_dir():
                continue
            for f in iter_entries(base):
                if f.name.startswith(".") or f.name.endswith(".log.md") or in_releases(f, root):
                    continue
                lg = f.parent / (f.stem + ".log.md")
                if not lg.exists():
                    lg.write_text(entry("建档", f"为 {f.name} 补建日志"), encoding="utf-8", newline="\n")
                    actions.append(f"补建日志 {lg.relative_to(root).as_posix()}")

    # 4) 程序项目：顶层文档与功能文档骨架
    docs = root / "docs"
    if "软件" in header.get("项目类型", "") and docs.is_dir():
        for nm in REQUIRED_SW_DOCS:
            if (docs / nm).exists():
                continue
            tpl = SOFTWARE_TPL_DIR / nm
            content = tpl.read_text(encoding="utf-8") if tpl.exists() else f"# {nm}\n\n（模板缺失）\n"
            (docs / nm).write_text(content, encoding="utf-8", newline="\n")
            actions.append(f"补建顶层文档 docs/{nm}")
        for row in parse_progress_rows(root, docs):
            if row["status"] in PROGRESS_TODO:
                continue
            expected = row["doc"] if row["doc"] not in ("", "—", "-") else f"docs/features/{row['name']}.md"
            if (root / expected).exists():
                continue
            t = root / expected
            t.parent.mkdir(parents=True, exist_ok=True)
            t.write_text(FEATURE_SKELETON.format(name=row["name"]), encoding="utf-8", newline="\n")
            actions.append(f"补建功能文档 {expected}")
    return actions


def run_project_check(root: Path) -> None:
    agents = root / "AGENTS.md"
    if not agents.exists():
        add("E", "缺规范文件", "AGENTS.md", 0, "项目未初始化：没有 AGENTS.md，任何 agent 都无从知道规矩")
        return
    text = agents.read_text(encoding="utf-8", errors="replace")
    header = parse_header(text)
    rows = parse_structure(text)
    legacy = rows is None
    if legacy:  # 1.x：按实际存在的经典目录兜底
        rows = [(p, "", "是") for p in ("docs/", "code/", "tmp/") if (root / p.rstrip("/")).is_dir()]

    declared_dirs = [p.rstrip("/") for p, _, _ in rows if p.endswith("/")]
    tracked_dirs = [p.rstrip("/") for p, _, t in rows if p.endswith("/") and t == "是"]
    declared_paths = {p.rstrip("/") for p, _, _ in rows}
    # 参与内容检查的目录：排除记忆（日志本就带口语摘要）与临时区
    scan_dirs = [root / d for d in tracked_dirs if d not in ("memory", "tmp", "temp")]

    # 1) 底线：git
    if not (root / ".git").exists():
        add("E", "未用 git 管理", ".git", 0, "底线要求：项目必须是 git 仓库，历史与回滚都依赖它")

    # 2) 底线：项目记忆与日志（含模型署名）
    check_memory(root, legacy)

    # 3) 结构：声明了却没建
    for d in declared_dirs:
        if not (root / d).is_dir():
            add("W", "目录缺失", d + "/", 0, "AGENTS.md 结构表声明了该目录，但实际不存在")

    # 4) 根目录散落
    allowed_set = set(ALLOWED_ROOT) | declared_paths
    cfg = root / ".allowed_root"
    if cfg.exists():
        for line in cfg.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                allowed_set.add(line.strip("/"))
    for entry in sorted(root.iterdir()):
        if entry.name in allowed_set or entry.name.startswith("."):
            continue
        add("W", "根目录散落文件", entry.name, 0,
            "不在结构表里：要么移入已声明目录，要么在 AGENTS.md 结构表登记它的职责")

    # 5) 版本副本增殖（releases 快照豁免）
    for base in scan_dirs:
        if not base.is_dir():
            continue
        for f in iter_entries(base):
            if f.name == ".gitkeep" or in_releases(f, root):
                continue
            if VERSIONISH.search(f.name):
                add("E", "版本副本增殖", f.relative_to(root).as_posix(), 0, "应就地迭代原文件，历史交给 git")

    # 6) 正式产出 AI 痕迹 + 逐文件日志配对
    per_file = header.get("日志模式", "") == "逐文件"
    for base in scan_dirs:
        if not base.is_dir():
            continue
        for f in iter_entries(base):
            if f.name.startswith(".") or in_releases(f, root):
                continue
            rel = f.relative_to(root).as_posix()
            if f.name.endswith(".log.md"):
                if "模型：" not in f.read_text(encoding="utf-8", errors="replace") and \
                   "修改者" not in f.read_text(encoding="utf-8", errors="replace"):
                    add("W", "日志空壳", rel, 0, "日志存在但无任何条目，应按格式补记录")
                continue
            if f.suffix == ".md":
                scan_markdown(f, rel)
            if per_file and not (f.parent / (f.stem + ".log.md")).exists():
                add("W", "缺修改日志", rel, 0, f"日志模式为「逐文件」，应有同名日志 {f.stem}.log.md")

    # 7) 代码注释 AI 痕迹
    scan_code_comments(root, scan_dirs)

    # 8) 命名规范
    scan_names(root, scan_dirs)

    # 9) 程序项目：顶层文档 + 台账一致性
    docs = root / "docs"
    if "软件" in header.get("项目类型", "") and "docs" in declared_dirs:
        for nm in REQUIRED_SW_DOCS:
            if not (docs / nm).exists():
                add("W", "缺顶层文档", f"docs/{nm}", 0,
                    "项目类型为软件，应有 PRD / Design / TDD / 开发进度 四份顶层文档")
        check_progress_consistency(root, docs)

    # 10) tmp 纪律与 git 状态
    tmp = root / "tmp"
    if (root / ".git").is_dir():
        _, tracked = run_git(root, "ls-files", "tmp/")
        if tracked.strip():
            add("W", "tmp 被 git 跟踪", "tmp/", 0,
                "tmp/ 应被 .gitignore 忽略，已跟踪文件: " + ", ".join(tracked.split()[:5]))
        _, status = run_git(root, "status", "--porcelain")
        untracked = []
        for line in status.splitlines():
            if not line.startswith("?? "):
                continue
            p = line[3:].strip().strip('"').replace("\\", "/")
            if p.startswith("tmp") or Path(p).name.startswith("."):
                continue
            untracked.append(p)
        if untracked:
            shown = ", ".join(untracked[:5]) + ("…" if len(untracked) > 5 else "")
            add("W", "未跟踪正式文件", shown, 0, f"共 {len(untracked)} 项，收工前应提交")
        n_changes = sum(1 for l in status.splitlines() if l.strip() and not l.startswith("?? "))
        if n_changes:
            add("I", "未提交变更", "", 0, f"{n_changes} 项改动待提交")
    if tmp.is_dir():
        n_tmp = sum(1 for _ in iter_entries(tmp))
        if n_tmp > 30:
            add("I", "临时区积压", "tmp/", 0, f"{n_tmp} 个临时文件，建议清理或转正")


def find_projects(base: Path, depth: int) -> list[Path]:
    found: list[Path] = []
    base_parts = len(base.parts)

    def walk(cur: Path) -> None:
        if (cur / "AGENTS.md").exists():
            found.append(cur)
            return
        if len(cur.parts) - base_parts >= depth:
            return
        try:
            entries = sorted(cur.iterdir())
        except OSError:
            return
        for e in entries:
            if e.is_dir() and e.name not in SKIP_DIRS and not e.name.startswith("."):
                walk(e)

    walk(base)
    return found


def print_findings(fs: list[dict]) -> dict[str, int]:
    icon = {"E": "[E]", "W": "[W]", "I": "[I]"}
    for f in fs:
        loc = f"{f['file']}:{f['line']}" if f["line"] else f["file"]
        print(f"{icon[f['level']]} {f['kind']}  {loc}  {f['detail']}")
    return {lv: sum(1 for f in fs if f["level"] == lv) for lv in "EWI"}


def main() -> int:
    ap = argparse.ArgumentParser(description="project-init 规范巡检（默认只读；--fix 做无争议修复）")
    ap.add_argument("target", nargs="?", default=".", help="项目目录（--scan 时为搜索根目录）")
    ap.add_argument("--json", action="store_true", help="以 JSON 输出")
    ap.add_argument("--fix", action="store_true", help="自动补目录/记忆/日志/顶层文档/功能文档骨架（其余仍需人工）")
    ap.add_argument("--model", default=None, help="当前 agent 的模型官方名，写入 --fix 补建的日志条目")
    ap.add_argument("--scan", action="store_true", help="批量巡检目标目录下所有含 AGENTS.md 的项目")
    ap.add_argument("--depth", type=int, default=2, help="--scan 的搜索深度（默认 2 层）")
    args = ap.parse_args()

    root = Path(args.target).expanduser().resolve()
    if not root.exists():
        print(f"[错误] 目录不存在: {root}")
        return 1

    if args.scan:
        projects = find_projects(root, max(0, args.depth))
        if not projects:
            print("未发现含 AGENTS.md 的项目")
            return 0
        report: dict[str, list] = {}
        totals = {"E": 0, "W": 0, "I": 0}
        any_e = False
        for i, p in enumerate(projects, 1):
            findings.clear()
            run_project_check(p)
            snap = [dict(f) for f in findings]
            report[str(p)] = snap
            c = {lv: sum(1 for f in snap if f["level"] == lv) for lv in "EWI"}
            if not args.json:
                print_findings(snap)
                print(f"== [{i}/{len(projects)}] {p}  (E{c['E']} W{c['W']} I{c['I']}) ==\n")
            for lv in totals:
                totals[lv] += c[lv]
            any_e = any_e or c["E"] > 0
        if args.json:
            print(json.dumps(report, ensure_ascii=False, indent=2))
        else:
            print(f"=== 批量巡检汇总: {len(projects)} 个项目, 合计 {totals['E']} 错误 / {totals['W']} 警告 / {totals['I']} 提示 ===")
        return 1 if any_e else 0

    findings.clear()
    if args.fix:
        agents = root / "AGENTS.md"
        text = agents.read_text(encoding="utf-8", errors="replace") if agents.exists() else ""
        header = parse_header(text)
        rows = parse_structure(text)
        actions = fix_project(root, (args.model or "").strip(), rows, header)
        if actions:
            print("=== --fix 已执行 ===")
            for a in actions:
                print("  + " + a)
            print()
        else:
            print("=== --fix: 无可自动修复项 ===\n")
    run_project_check(root)
    if args.json:
        print(json.dumps(findings, ensure_ascii=False, indent=2))
    else:
        c = print_findings(findings)
        print(f"\n=== 巡检结果: {c['E']} 错误 / {c['W']} 警告 / {c['I']} 提示 ===")
        print("结论: " + ("存在违规，须修复" if c["E"] else ("可接受，建议处理警告" if c["W"] else "规范通过")))
    return 1 if any(f["level"] == "E" for f in findings) else 0


if __name__ == "__main__":
    sys.exit(main())
