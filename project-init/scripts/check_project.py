def parse_header(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for key in ("项目名称", "项目类型", "技术栈", "规范版本", "日志模式"):
        m = re.search(rf"^-\s*{key}[：:]\s*(.+)$", text, re.M)
        if m:
            out[key] = m.group(1).strip()
    return out


def parse_structure(text: str) -> list[tuple[str, str, str]] | None:
    """解析 structure 区块的结构表；返回 [(路径, 职责, 入库)]，无区块返回 None。"""
    m = re.search(r"<!--\s*structure:begin\s*-->(.*?)<!--\s*structure:end\s*-->", text, re.S)
    if not m:
        return None
    rows: list[tuple[str, str, str]] = []
    for line in m.group(1).splitlines():
        s = line.strip()
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if len(cells) < 3 or all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
            continue
        path = cells[0].strip("`").strip()
        if not path or path in ("路径", "位置"):
            continue
        rows.append((path, cells[1], cells[2]))
    return rows


