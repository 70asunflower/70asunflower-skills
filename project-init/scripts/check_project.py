def scan_markdown(path: Path, rel: str) -> None:
    try:
        raw = path.read_bytes()
    except OSError as e:
        add("W", "读取失败", rel, 0, str(e))
        return
    try:
        raw.decode("utf-8")
    except UnicodeDecodeError:
        add("W", "非UTF-8编码", rel, 0, "中文短语匹配会失效，建议转存为 UTF-8")
        return
    text = raw.decode("utf-8", errors="replace")
    in_fence = False
    for i, ln in enumerate(text.splitlines(), 1):
        if ln.strip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        clean = re.sub(r"`[^`]*`", " ", ln)
        if CHANGELOG_HEADING.match(clean.strip()):
            add("E", "正文内修订历史", rel, i, "修订记录应写进日志，不得出现在正文章节")
            continue
        for p in AI_PHRASES_E:
            if p in clean:
                add("E", "对话腔/AI声明", rel, i, f"命中「{p}」")
        for p in AI_PHRASES_W:
            if p in clean:
                add("W", "AI词汇(需复核)", rel, i, f"命中「{p}」")
        hits = sorted({ch for ch in clean if is_emoji(ch)})
        if hits:
            add("E", "emoji", rel, i, "字符: " + " ".join(hits))


def scan_names(root: Path, bases: list[Path]) -> None:
    for base in bases:
        if not base.is_dir():
            continue
        for f in iter_entries(base):
            if f.name == ".gitkeep" or in_releases(f, root):
                continue
            rel = f.relative_to(root).as_posix()
            stem = f.stem
            bad = sorted({ch for ch in f.name if ch in BAD_NAME_CHARS})
            if bad:
                add("W", "命名不规范", rel, 0, "含空格/特殊字符: " + " ".join(repr(c) for c in bad))
            if PLACEHOLDER_NAME.match(stem):
                add("W", "命名不规范", rel, 0, "占位/无意义命名，应改为见名知义的名称")
            if DUPLICATE_NAME.search(stem):
                add("W", "命名不规范", rel, 0, "疑似重复副本命名（如「(1)」），应就地迭代或交给 git")
            if DATE_IN_NAME.search(stem):
                add("W", "命名不规范", rel, 0, "正式文件名含日期，时效信息应交给 git 与日志")


def scan_code_comments(root: Path, bases: list[Path]) -> None:
    for base in bases:
        if not base.is_dir():
            continue
        for f in iter_entries(base):
            if f.suffix.lower() not in CODE_EXTS:
                continue
            rel = f.relative_to(root).as_posix()
            try:
                text = f.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            for i, ln in enumerate(text.splitlines(), 1):
                s = ln.strip()
                if not s.startswith(COMMENT_PREFIXES):
                    continue
                for p in AI_PHRASES_E:
                    if p in s:
                        add("E", "注释AI痕迹", rel, i, f"命中「{p}」")
                hits = sorted({ch for ch in s if is_emoji(ch)})
                if hits:
                    add("E", "注释emoji", rel, i, "字符: " + " ".join(hits))


def in_releases(f: Path, root: Path) -> bool:
    return "releases" in f.relative_to(root).parts[:-1]


def check_memory(root: Path, legacy: bool) -> None:
    """底线：项目记忆与日志，日志条目必须带模型 id。"""
    mem = root / "memory"
    if legacy:
        if not (mem / "MEMORY.md").exists():
            add("W", "建议升级", "AGENTS.md", 0,
                "本项目 AGENTS.md 为 1.x（无结构表、无 memory 约定），建议用 init_project.py --upgrade 迁移")
        return
    if not (mem / "MEMORY.md").exists():
        add("E", "缺项目记忆", "memory/MEMORY.md", 0,
            "底线要求：长期记忆文件必须存在（init_project.py 可补建）")
    if not mem.is_dir():
        return
    logs = sorted(p for p in mem.glob("*.md") if LOG_DATE.match(p.name))
    if not logs:
        add("E", "缺工作日志", "memory/", 0,
            "底线要求：memory/<YYYY-MM-DD>.md 工作日志至少一份（init_project.py 可补建）")
        return
    # 每条 ## 条目必须有「模型：」
    for f in logs:
        rel = f.relative_to(root).as_posix()
        try:
            lines = f.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        entries: list[tuple[int, str]] = []
        for i, ln in enumerate(lines, 1):
            if ln.startswith("## "):
                entries.append((i, ln))
        if not entries:
            add("W", "日志空壳", rel, 0, "日志存在但无「## 时间 — 摘要」条目")
            continue
        for idx, (line_no, _) in enumerate(entries):
            end = entries[idx + 1][0] - 1 if idx + 1 < len(entries) else len(lines)
            block = "\n".join(lines[line_no - 1:end])
            if "模型：" not in block and "模型:" not in block:
                add("E", "日志缺模型", rel, line_no, "每条日志必须写明「模型：<模型官方名>」")
    # 最近一份是否太久没更新
    last = logs[-1].name[:-3]
    try:
        d = datetime.strptime(last, "%Y-%m-%d").date()
        gap = (datetime.now().date() - d).days
        if gap > LOG_STALE_DAYS:
            add("W", "日志久未更新", f"memory/{logs[-1].name}", 0,
                f"最近一条日志距今 {gap} 天，有改动应追加当日日志")
    except ValueError:
        pass
    if len(logs) > 60:
        add("I", "日志偏多", "memory/", 0,
            f"{len(logs)} 份日日志，可把已失效内容归并进 MEMORY.md 后删除旧文件（git 留底）")


def parse_progress_rows(root: Path, docs: Path) -> list[dict]:
    prog = docs / "开发进度.md"
    rows: list[dict] = []
    if not prog.exists():
        return rows
    try:
        text = prog.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return rows
    section = ""
    for i, ln in enumerate(text.splitlines(), 1):
        s = ln.strip()
        if s.startswith("## "):
            section = s[3:].strip()
            continue
        if "功能进度" not in section or not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if len(cells) < 4 or all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
            continue
        name, status, doccell = cells[1], cells[2], cells[3]
        if name in ("", "功能点"):
            continue
        rows.append({"line": i, "name": name, "status": status, "doc": doccell})
    return rows


def check_progress_consistency(root: Path, docs: Path) -> None:
    for row in parse_progress_rows(root, docs):
        if row["status"] in PROGRESS_TODO:
            continue
        expected = row["doc"] if row["doc"] not in ("", "—", "-") else f"docs/features/{row['name']}.md"
        target = root / expected
        if not target.exists():
            add("W", "功能文档缺失", "docs/开发进度.md", row["line"],
                f"功能「{row['name']}」状态为「{row['status']}」，但缺少 {expected}")
            continue
        if target.suffix != ".md":
            continue
        try:
            ftext = target.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        m = re.search(r"^\s*-\s*\*{0,2}状态\*{0,2}[：:]\s*([^\s（(*]+)", ftext, re.M)
        if not m:
            add("W", "功能文档缺状态", expected, 0, "应有「- 状态：」字段（待办/开发中/待测试/测试通过/已审核）")
            continue
        doc_status = m.group(1).strip().strip("*")
        if doc_status not in KNOWN_STATUS:
            add("W", "功能文档状态异常", expected, 0, f"「{doc_status}」不在标准状态集内")
        elif doc_status != row["status"]:
            add("E", "状态不一致", expected, 0,
                f"台账为「{row['status']}」、功能文档为「{doc_status}」，须人工核对统一（审核门禁）")


